export function getCircuitDetails(gpName?: string, countryRaw?: string, circuitId?: string): CircuitDetails {
	const candidates = [
		circuitId?.toLowerCase().trim(),
		countryRaw?.toLowerCase().trim(),
		gpName?.toLowerCase().trim(),
	].filter(Boolean) as string[];

	for (const candidate of candidates) {
		for (const circuit of Object.values(CIRCUITS_DATABASE)) {
			if (circuit.aliases.some((alias) => candidate.includes(alias))) {
				return circuit;
			}
		}
	}

	return DEFAULT_CIRCUIT;
}

export function getCircuitBackdropUrl(gpName?: string, countryRaw?: string, circuitId?: string): string {
	return getCircuitDetails(gpName, countryRaw, circuitId).imageUrl;
}
